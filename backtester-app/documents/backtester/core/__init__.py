"""
Core type definitions for the backtesting engine.
Dataclasses for Bar, Signal, Trade, Position, and PlaybookStep.
"""

from __future__ import annotations
from dataclasses import dataclass, field
from datetime import datetime
from enum import Enum
from typing import Any, Optional


class Direction(Enum):
    LONG = "LONG"
    SHORT = "SHORT"


class OrderType(Enum):
    MARKET = "MARKET"
    LIMIT = "LIMIT"
    STOP = "STOP"


class TradeStatus(Enum):
    OPEN = "OPEN"
    CLOSED = "CLOSED"
    CANCELLED = "CANCELLED"


@dataclass
class Bar:
    """Single OHLCV bar."""
    time: datetime
    open: float
    high: float
    low: float
    close: float
    tick_volume: int = 0
    spread: int = 0

    @property
    def is_bullish(self) -> bool:
        return self.close > self.open

    @property
    def is_bearish(self) -> bool:
        return self.close < self.open

    @property
    def body_high(self) -> float:
        return max(self.open, self.close)

    @property
    def body_low(self) -> float:
        return min(self.open, self.close)

    @property
    def body_size(self) -> float:
        return abs(self.close - self.open)

    @property
    def upper_wick(self) -> float:
        return self.high - self.body_high

    @property
    def lower_wick(self) -> float:
        return self.body_low - self.low

    @property
    def total_range(self) -> float:
        return self.high - self.low

    @property
    def midpoint(self) -> float:
        return (self.high + self.low) / 2.0


@dataclass
class Signal:
    """A trading signal generated by a strategy."""
    strategy_id: str
    direction: Direction
    entry_price: float
    stop_loss: float
    take_profit: float
    timestamp: datetime
    symbol: str
    order_type: OrderType = OrderType.MARKET
    risk_reward: float = 0.0
    metadata: dict[str, Any] = field(default_factory=dict)

    def __post_init__(self):
        if self.stop_loss and self.take_profit and self.entry_price:
            risk = abs(self.entry_price - self.stop_loss)
            reward = abs(self.take_profit - self.entry_price)
            self.risk_reward = round(reward / risk, 2) if risk > 0 else 0.0


@dataclass
class StepRecord:
    """A single strategy step execution record."""
    step_name: str
    step_number: int
    timestamp: datetime
    price_level: float
    timeframe: str
    description: str
    metadata: dict[str, Any] = field(default_factory=dict)


@dataclass
class Trade:
    """A completed or open trade with full audit trail."""
    id: int
    strategy_id: str
    symbol: str
    direction: Direction
    entry_time: datetime
    entry_price: float
    stop_loss: float
    take_profit: float
    exit_time: Optional[datetime] = None
    exit_price: Optional[float] = None
    pnl: float = 0.0
    pnl_pips: float = 0.0
    pnl_usd: float = 0.0
    risk_reward_achieved: float = 0.0
    status: TradeStatus = TradeStatus.OPEN
    steps: list[StepRecord] = field(default_factory=list)
    metadata: dict[str, Any] = field(default_factory=dict)

    def close(
        self,
        exit_time: datetime,
        exit_price: float,
        pip_value: float = 0.0001,
        lot_size: float = 0.01,
        pip_value_usd: float = 10.0,
    ):
        """Close the trade and calculate price + USD PnL."""
        self.exit_time = exit_time
        self.exit_price = exit_price
        self.status = TradeStatus.CLOSED

        if self.direction == Direction.LONG:
            self.pnl = exit_price - self.entry_price
        else:
            self.pnl = self.entry_price - exit_price

        if pip_value > 0:
            self.pnl_pips = self.pnl / pip_value

        self.pnl_usd = self.pnl_pips * pip_value_usd * lot_size

        risk = abs(self.entry_price - self.stop_loss)
        if risk > 0:
            self.risk_reward_achieved = round(self.pnl / risk, 2)


@dataclass
class Position:
    """An open position being tracked by the portfolio."""
    trade: Trade
    lot_size: float = 0.01
    current_sl: float = 0.0
    current_tp: float = 0.0
    break_even_applied: bool = False

    def __post_init__(self):
        self.current_sl = self.trade.stop_loss
        self.current_tp = self.trade.take_profit

    def move_sl_to_breakeven(self):
        """Move stop loss to entry price."""
        self.current_sl = self.trade.entry_price
        self.break_even_applied = True

    def update_sl(self, new_sl: float):
        """Update stop loss level."""
        self.current_sl = new_sl

    def is_sl_hit(self, bar: Bar) -> bool:
        """Check if stop loss was hit during this bar."""
        if self.trade.direction == Direction.LONG:
            return bar.low <= self.current_sl
        else:
            return bar.high >= self.current_sl

    def is_tp_hit(self, bar: Bar) -> bool:
        """Check if take profit was hit during this bar."""
        if self.trade.direction == Direction.LONG:
            return bar.high >= self.current_tp
        else:
            return bar.low <= self.current_tp


