@dataclass
class BacktestConfig:
    """Configuration for a backtest run."""
    strategy_id: str
    symbol: str
    start_date: datetime
    end_date: datetime
    initial_balance: float = 10000.0
    risk_per_trade: float = 0.01  # 1% risk
    spread_pips: float = 1.0
    slippage_pips: float = 0.5
    commission_per_lot: float = 7.0  # USD per round trip


@dataclass
class BacktestResult:
    """Complete results from a backtest run."""
    config: BacktestConfig
    trades: list[Trade] = field(default_factory=list)
    equity_curve: list[dict[str, Any]] = field(default_factory=list)
    total_trades: int = 0
    winning_trades: int = 0
    losing_trades: int = 0
    win_rate: float = 0.0
    profit_factor: float = 0.0
    max_drawdown: float = 0.0
    max_drawdown_pct: float = 0.0
    total_pnl: float = 0.0
    sharpe_ratio: float = 0.0
    avg_rr: float = 0.0
    avg_trade_duration: float = 0.0  # in minutes

    def compute_stats(self):
        """Calculate all performance statistics from the trade list."""
        self.total_trades = len(self.trades)
        if self.total_trades == 0:
            return

        winners = [t for t in self.trades if t.metadata.get("pnl_usd", t.pnl_usd) > 0]
        losers = [t for t in self.trades if t.metadata.get("pnl_usd", t.pnl_usd) <= 0]
        self.winning_trades = len(winners)
        self.losing_trades = len(losers)
        self.win_rate = round(self.winning_trades / self.total_trades * 100, 2)

        gross_profit = sum(t.metadata.get("pnl_usd", t.pnl_usd) for t in winners if t.metadata.get("pnl_usd", t.pnl_usd) > 0) if winners else 0
        gross_loss = abs(sum(t.metadata.get("pnl_usd", t.pnl_usd) for t in losers if t.metadata.get("pnl_usd", t.pnl_usd) <= 0)) if losers else 0
        self.profit_factor = round(gross_profit / gross_loss, 2) if gross_loss > 0 else float("inf")

        self.total_pnl = round(sum(t.metadata.get("pnl_usd", t.pnl_usd) for t in self.trades), 2)
        self.avg_rr = round(
            sum(t.risk_reward_achieved for t in self.trades) / self.total_trades, 2
        )

        # Max drawdown from equity curve
        if self.equity_curve:
            peak = self.equity_curve[0].get("equity", self.config.initial_balance)
            max_dd = 0
            for point in self.equity_curve:
                eq = point.get("equity", peak)
                if eq > peak:
                    peak = eq
                dd = peak - eq
                if dd > max_dd:
                    max_dd = dd
            self.max_drawdown = round(max_dd, 2)
            self.max_drawdown_pct = round(
                max_dd / self.config.initial_balance * 100, 2
            ) if self.config.initial_balance > 0 else 0

        # Average trade duration
        durations = []
        for t in self.trades:
            if t.exit_time and t.entry_time:
                dur = (t.exit_time - t.entry_time).total_seconds() / 60
                durations.append(dur)
        self.avg_trade_duration = round(
            sum(durations) / len(durations), 1
        ) if durations else 0

        # Sharpe ratio (simplified daily returns)
        if len(self.equity_curve) > 1:
            returns = []
            for i in range(1, len(self.equity_curve)):
                prev = self.equity_curve[i - 1].get("equity", 0)
                curr = self.equity_curve[i].get("equity", 0)
                if prev > 0:
                    returns.append((curr - prev) / prev)
            if returns:
                import statistics
                mean_ret = statistics.mean(returns)
                std_ret = statistics.stdev(returns) if len(returns) > 1 else 1
                self.sharpe_ratio = round(
                    (mean_ret / std_ret) * (252 ** 0.5), 2
                ) if std_ret > 0 else 0

    def to_dict(self) -> dict:
        """Serialize to JSON-friendly dict."""
        return {
            "config": {
                "strategy_id": self.config.strategy_id,
                "symbol": self.config.symbol,
                "start_date": self.config.start_date.isoformat(),
                "end_date": self.config.end_date.isoformat(),
                "initial_balance": self.config.initial_balance,
                "risk_per_trade": self.config.risk_per_trade,
            },
            "stats": {
                "total_trades": self.total_trades,
                "winning_trades": self.winning_trades,
                "losing_trades": self.losing_trades,
                "win_rate": self.win_rate,
                "profit_factor": self.profit_factor,
                "max_drawdown": self.max_drawdown,
                "max_drawdown_pct": self.max_drawdown_pct,
                "total_pnl": round(self.total_pnl, 2),
                "sharpe_ratio": self.sharpe_ratio,
                "avg_rr": self.avg_rr,
                "avg_trade_duration_mins": self.avg_trade_duration,
            },
            "equity_curve": self.equity_curve,
            "trades": [
                {
                    "id": t.id,
                    "strategy_id": t.strategy_id,
                    "symbol": t.symbol,
                    "direction": t.direction.value,
                    "entry_time": t.entry_time.isoformat(),
                    "entry_price": t.entry_price,
                    "stop_loss": t.stop_loss,
                    "take_profit": t.take_profit,
                    "exit_time": t.exit_time.isoformat() if t.exit_time else None,
                    "exit_price": t.exit_price,
                    "pnl": round(t.pnl, 5),
                    "pnl_pips": round(t.pnl_pips, 1),
                    "pnl_usd": round(t.pnl_usd, 2),
                    "rr_achieved": t.risk_reward_achieved,
                    "status": t.status.value,
                    "steps": [
                        {
                            "step_name": s.step_name,
                            "step_number": s.step_number,
                            "timestamp": s.timestamp.isoformat(),
                            "price_level": s.price_level,
                            "timeframe": s.timeframe,
                            "description": s.description,
                        }
                        for s in t.steps
                    ],
                }
                for t in self.trades
            ],
        }
